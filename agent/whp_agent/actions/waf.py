"""Web application firewall: ModSecurity v3 with the OWASP Core Rule Set.

The installer (module waf) loads the rules once for all websites, switched off.
The panel owns the settings and sends all of them with every ``waf.apply``:

* ``/etc/nginx/whp/waf/server.conf``: paranoia level and anomaly threshold
  (before the CRS rules, which read them while they start up).
* ``/etc/nginx/whp/waf/server-exceptions.conf``: exceptions for every site
  (after the CRS rules).
* per site in block or detect mode:
  ``/etc/nginx/whp/sites/<domain>/20-waf.conf`` (switches ModSecurity on in the
  site's server blocks, aliases included) and
  ``/etc/nginx/whp/waf/sites/<domain>.conf`` (rule engine On or DetectionOnly,
  plus the site's exceptions). A site in mode off has neither file.

``nginx -t`` checks everything before Nginx is reloaded; on a failure the
previous files are put back. ``waf.events`` reads the JSON audit log from a
cursor, so the panel collects every match once.
"""

import fcntl
import json
import os
import re
import time
from contextlib import contextmanager
from pathlib import Path

from .. import paths
from .. import validate as v
from ..registry import ActionError, action
from ..run import run

NGINX_SITES = Path(os.environ.get("WHP_NGINX_SITES", "/etc/nginx/whp/sites"))
WAF_DIR = Path(os.environ.get("WHP_WAF_DIR", "/etc/nginx/whp/waf"))
HTTP_CONF = Path(os.environ.get("WHP_WAF_HTTP_CONF", "/etc/nginx/conf.d/whp-waf.conf"))
AUDIT_LOG = Path(os.environ.get("WHP_WAF_AUDIT_LOG", "/var/log/modsecurity/audit.log"))
LOCK_FILE = Path(os.environ.get("WHP_WAF_LOCK", os.path.join(paths.STATE_DIR, "waf.lock")))
RELOAD = os.environ.get("WHP_WAF_RELOAD", "1") != "0"  # tests switch nginx off

SITE_INCLUDE = "20-waf.conf"
HEADER = "# Generated by whp-agent (waf.apply). Changes are overwritten from the panel.\n"
MODES = ("block", "detect", "off")
SITE_RULE_BASE = 10000  # ids of our per-site exception rules
SERVER_RULE_BASE = 20000  # ids of our server-wide exception rules
MAX_EXCEPTIONS = 200
# Rules that only add up the score; an event names the rules that matched.
SCORING_RULES = {949110, 949111, 959100, 959101, 980130, 980140, 980170}
BLOCKING_RULES = {949110, 949111, 959100, 959101, 200002}

_PATH = re.compile(r"/[A-Za-z0-9._~%/+:@=,-]{0,200}")
_PARAM = re.compile(r"[A-Za-z0-9_.\-\[\]]{1,100}")
_SCORE = re.compile(r"Total Score: (\d+)")


# ---------------------------------------------------------------- validation

def _exception(item, where):
    if not isinstance(item, dict):
        raise ActionError("invalid_params", f"{where}: an exception must be an object")
    rule = v.integer(item, "rule", minimum=1, maximum=99_999_999)
    path = v.string(item, "path", required=False, max_len=201) or None
    param = v.string(item, "param", required=False, max_len=100) or None
    if path is not None and not _PATH.fullmatch(path):
        raise ActionError("invalid_params", f"{where}: path must start with / and may not contain spaces or quotes")
    if param is not None and not _PARAM.fullmatch(param):
        raise ActionError("invalid_params", f"{where}: parameter name has invalid characters")
    return {"rule": rule, "path": path, "param": param}


def _exceptions(value, where):
    if value is None:
        return []
    if not isinstance(value, list) or len(value) > MAX_EXCEPTIONS:
        raise ActionError("invalid_params", f"{where}: at most {MAX_EXCEPTIONS} exceptions")
    out = []
    for item in value:
        e = _exception(item, where)
        if e not in out:
            out.append(e)
    return out


def parse_config(params):
    cfg = {
        "paranoia": v.integer(params, "paranoia", required=False, default=1, minimum=1, maximum=4),
        "threshold": v.integer(params, "threshold", required=False, default=5, minimum=2, maximum=100),
        "exceptions": _exceptions(params.get("exceptions"), "exceptions"),
        "sites": [],
    }
    sites = params.get("sites") or []
    if not isinstance(sites, list) or len(sites) > 10_000:
        raise ActionError("invalid_params", "sites must be a list")
    seen = set()
    for item in sites:
        if not isinstance(item, dict):
            raise ActionError("invalid_params", "every site must be an object")
        domain = v.domain(item, "domain")
        if domain in seen:
            raise ActionError("invalid_params", f"{domain} is listed twice")
        seen.add(domain)
        cfg["sites"].append({
            "domain": domain,
            "mode": v.choice(item, "mode", MODES),
            "exceptions": _exceptions(item.get("exceptions"), domain),
        })
    return cfg


# ---------------------------------------------------------------- rendering

def render_exceptions(exceptions, base):
    lines = []
    for i, e in enumerate(exceptions):
        rule, path, param = e["rule"], e["path"], e["param"]
        if path is None and param is None:
            lines.append(f"SecRuleRemoveById {rule}")
        elif path is None:
            lines.append(f'SecRuleUpdateTargetById {rule} "!ARGS:{param}"')
        else:
            ctl = f"ctl:ruleRemoveTargetById={rule};ARGS:{param}" if param else f"ctl:ruleRemoveById={rule}"
            lines.append(f'SecRule REQUEST_FILENAME "@beginsWith {path}" "id:{base + i},phase:1,pass,t:none,nolog,{ctl}"')
    return lines


def render_server(cfg):
    p, t = cfg["paranoia"], cfg["threshold"]
    return HEADER + (
        f'SecAction "id:900000,phase:1,pass,t:none,nolog,setvar:tx.blocking_paranoia_level={p},setvar:tx.paranoia_level={p}"\n'
        f'SecAction "id:900110,phase:1,pass,t:none,nolog,setvar:tx.inbound_anomaly_score_threshold={t},'
        f'setvar:tx.outbound_anomaly_score_threshold=4"\n'
    )


def render_server_exceptions(cfg):
    lines = render_exceptions(cfg["exceptions"], SERVER_RULE_BASE)
    return HEADER + "# Exceptions for every website.\n" + "".join(line + "\n" for line in lines)


def render_site_rules(site):
    engine = "On" if site["mode"] == "block" else "DetectionOnly"
    lines = [f"SecRuleEngine {engine}"] + render_exceptions(site["exceptions"], SITE_RULE_BASE)
    return HEADER + f"# {site['domain']}: {site['mode']}\n" + "".join(line + "\n" for line in lines)


def render_site_include(site):
    d = site["domain"]
    return HEADER + (
        f"# Web application firewall for {d}: {site['mode']}\n"
        "modsecurity on;\n"
        f'modsecurity_transaction_id "{d}~$request_id";\n'
        f"modsecurity_rules_file {WAF_DIR}/sites/{d}.conf;\n"
    )


# ---------------------------------------------------------------- applying

def available():
    return HTTP_CONF.is_file() and (WAF_DIR / "main.conf").is_file()


@contextmanager
def _lock():
    LOCK_FILE.parent.mkdir(parents=True, exist_ok=True)
    with open(LOCK_FILE, "w") as fh:
        fcntl.flock(fh, fcntl.LOCK_EX)
        yield


def _snapshot(paths_):
    return {p: (p.read_bytes() if p.exists() else None) for p in paths_}


def _restore(snapshot):
    for p, content in snapshot.items():
        if content is None:
            p.unlink(missing_ok=True)
        else:
            p.write_bytes(content)


def _write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".tmp")
    tmp.write_text(text)
    os.chmod(tmp, 0o644)
    os.replace(tmp, path)


def _site_rules(domain):
    return WAF_DIR / "sites" / f"{domain}.conf"


def _site_include(domain):
    return NGINX_SITES / domain / SITE_INCLUDE


def _managed_domains():
    found = set()
    if (WAF_DIR / "sites").is_dir():
        found |= {p.stem for p in (WAF_DIR / "sites").glob("*.conf")}
    if NGINX_SITES.is_dir():
        found |= {p.parent.name for p in NGINX_SITES.glob(f"*/{SITE_INCLUDE}")}
    return found


def plan(cfg):
    """Files to write (path -> text) and to remove, plus sites that do not exist yet."""
    write, remove, missing = {}, set(), []
    write[WAF_DIR / "server.conf"] = render_server(cfg)
    write[WAF_DIR / "server-exceptions.conf"] = render_server_exceptions(cfg)
    wanted = set()
    for site in cfg["sites"]:
        d = site["domain"]
        if site["mode"] == "off":
            continue
        if not (NGINX_SITES / d).is_dir():
            missing.append(d)
            continue
        wanted.add(d)
        write[_site_rules(d)] = render_site_rules(site)
        write[_site_include(d)] = render_site_include(site)
    for d in _managed_domains() - wanted:
        remove |= {_site_rules(d), _site_include(d)}
    return write, remove, missing


def _reload():
    if not RELOAD:
        return
    try:
        run(["nginx", "-t"], timeout=120)
    except ActionError as e:
        raise ActionError("command_failed", "Nginx did not accept the firewall settings",
                          {"stderr": (e.details or {}).get("stderr", "")[-1500:]})
    run(["systemctl", "reload", "nginx"], timeout=60)


@action("waf.apply")
def apply(params):
    cfg = parse_config(params)
    if not available():
        raise ActionError("not_found", "The web application firewall is not installed on this server")
    with _lock():
        write, remove, missing = plan(cfg)
        snapshot = _snapshot(list(write) + list(remove))
        try:
            # Rules first, includes after: nginx never points at a missing file.
            for p in sorted(write, key=lambda p: p.name == SITE_INCLUDE):
                _write(p, write[p])
            for p in sorted(remove, key=lambda p: p.name != SITE_INCLUDE):
                p.unlink(missing_ok=True)
            _reload()
        except Exception:
            _restore(snapshot)
            raise
    modes = {s["domain"]: s["mode"] for s in cfg["sites"]}
    return {
        "applied_at": int(time.time()),
        "block": sum(1 for m in modes.values() if m == "block"),
        "detect": sum(1 for m in modes.values() if m == "detect"),
        "off": sum(1 for m in modes.values() if m == "off"),
        "missing": sorted(missing),
    }


def _pkg_version(*names):
    for name in names:
        try:
            out = run(["dpkg-query", "-W", "-f=${Version}", name], timeout=20, check=False)
        except ActionError:
            return None
        if out.returncode == 0 and out.stdout.strip():
            return out.stdout.strip()
    return None


@action("waf.status")
def status(params):
    ok = available()
    sites = {}
    for d in sorted(_managed_domains()):
        rules = _site_rules(d)
        if rules.is_file() and _site_include(d).is_file():
            sites[d] = "block" if "SecRuleEngine On" in rules.read_text() else "detect"
    return {
        "available": ok,
        "engine": _pkg_version("libmodsecurity3t64", "libmodsecurity3") if ok else None,
        "crs": _pkg_version("modsecurity-crs") if ok else None,
        "sites": sites,
        "log_size": AUDIT_LOG.stat().st_size if AUDIT_LOG.exists() else 0,
    }


# ---------------------------------------------------------------- events

def _header(headers, name):
    for k, val in (headers or {}).items():
        if k.lower() == name:
            return str(val)
    return ""


def _cut(text, n):
    text = str(text or "")
    return text if len(text) <= n else text[: n - 1] + "…"


def parse_event(line):
    """One audit log line -> the event the panel stores, or None when it is not ours or has no rule match."""
    try:
        doc = json.loads(line)
    except ValueError:
        return None
    tx = doc.get("transaction") if isinstance(doc, dict) else None
    if not isinstance(tx, dict):
        return None
    uid = str(tx.get("unique_id") or "")
    if "~" not in uid:
        return None
    domain, _, request_id = uid.rpartition("~")
    req = tx.get("request") or {}
    res = tx.get("response") or {}
    producer = tx.get("producer") or {}
    rules, score, matched_block = [], None, False
    for m in tx.get("messages") or []:
        d = m.get("details") or {}
        try:
            rid = int(d.get("ruleId") or 0)
        except (TypeError, ValueError):
            rid = 0
        if rid in (949110, 949111):
            found = _SCORE.search(str(m.get("message") or ""))
            score = int(found.group(1)) if found else score
        if rid in BLOCKING_RULES:
            matched_block = True
        if rid == 0 or rid in SCORING_RULES or any(r["id"] == rid for r in rules):
            continue
        try:
            severity = int(d.get("severity"))
        except (TypeError, ValueError):
            severity = None
        tags = [t for t in d.get("tags") or [] if isinstance(t, str) and t.startswith("attack-")]
        rules.append({
            "id": rid,
            "message": _cut(m.get("message"), 200),
            "data": _cut(d.get("data"), 200),
            "severity": severity,
            "tags": tags[:5],
        })
    if not rules:
        return None
    try:
        status_code = int(res.get("http_code") or 0)
    except (TypeError, ValueError):
        status_code = 0
    engine = str(producer.get("secrules_engine") or "")
    blocked = engine.lower() == "enabled" and status_code in (400, 403) and matched_block
    return {
        "id": _cut(request_id, 64),
        "domain": domain.lower(),
        "time": _cut(tx.get("time_stamp"), 40),
        "ip": _cut(tx.get("client_ip"), 45),
        "method": _cut(req.get("method"), 10),
        "uri": _cut(req.get("uri"), 500),
        "host": _cut(_header(req.get("headers"), "host"), 255),
        "user_agent": _cut(_header(req.get("headers"), "user-agent"), 255),
        "status": status_code,
        "blocked": blocked,
        "mode": "block" if engine.lower() == "enabled" else "detect",
        "score": score,
        "rules": rules[:20],
    }


def _read_from(path, offset, limit, events):
    """Parse lines from offset; returns the offset after the last complete line read."""
    with open(path, "rb") as fh:
        fh.seek(offset)
        while len(events) < limit:
            line = fh.readline()
            if not line or not line.endswith(b"\n"):
                break  # nothing more, or a line nginx is still writing
            offset += len(line)
            ev = parse_event(line.decode("utf-8", "replace"))
            if ev:
                events.append(ev)
    return offset


@action("waf.events")
def events(params):
    """New audit log entries since the cursor ({inode, offset}); a missing cursor starts at the end."""
    limit = v.integer(params, "limit", required=False, default=2000, minimum=1, maximum=5000)
    cursor = params.get("cursor")
    if cursor is not None and not isinstance(cursor, dict):
        raise ActionError("invalid_params", "cursor must be an object")
    out = []
    if not AUDIT_LOG.exists():
        # Starts from the top once nginx has written the first line.
        return {"events": out, "cursor": {"inode": 0, "offset": 0}, "more": False}
    st = AUDIT_LOG.stat()
    if not cursor:
        from_start = bool(params.get("from_start"))
        return {"events": out, "cursor": {"inode": st.st_ino, "offset": 0 if from_start else st.st_size}, "more": from_start and st.st_size > 0}
    inode = v.integer(cursor, "inode", minimum=0, maximum=2**63)
    offset = v.integer(cursor, "offset", minimum=0, maximum=2**63)
    if inode == st.st_ino and offset > st.st_size:
        # copytruncate: the rest of the old log is in audit.log.1.
        rotated = AUDIT_LOG.with_name(AUDIT_LOG.name + ".1")
        if rotated.exists() and rotated.stat().st_size >= offset:
            _read_from(rotated, offset, limit, out)
        offset = 0
    elif inode != st.st_ino:
        offset = 0
    offset = _read_from(AUDIT_LOG, offset, limit, out)
    return {"events": out, "cursor": {"inode": st.st_ino, "offset": offset}, "more": len(out) >= limit}
