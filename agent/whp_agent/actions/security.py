# ---------------------------------------------------------------- validation

def _service(params, name):
    raw = params.get(name)
    if raw is None:
        raw = {}
    if not isinstance(raw, dict):
        raise ActionError("invalid_params", f"services.{name} must be an object")
    d = DEFAULTS[name]
    cfg = {
        "enabled": v.boolean(raw, "enabled", required=False, default=d["enabled"]),
        "temp_after": v.integer(raw, "temp_after", required=False, default=d["temp_after"], minimum=1, maximum=1000),
        "window_minutes": v.integer(raw, "window_minutes", required=False, default=d["window_minutes"], minimum=1, maximum=1440),
        "ban_minutes": v.integer(raw, "ban_minutes", required=False, default=d["ban_minutes"], minimum=1, maximum=525600),
        "perm_after": v.integer(raw, "perm_after", required=False, default=d["perm_after"], minimum=0, maximum=10000),
        "perm_window_hours": v.integer(raw, "perm_window_hours", required=False, default=d["perm_window_hours"], minimum=1, maximum=720),
    }
    if cfg["perm_after"] and cfg["perm_after"] <= cfg["temp_after"]:
        raise ActionError("invalid_params", f"services.{name}.perm_after must be higher than temp_after (or 0 for off)")
    return cfg


def _network(value, field):
    if not isinstance(value, str) or len(value) > 64:
        raise ActionError("invalid_params", f"{field} must be an IP address or network")
    try:
        net = ipaddress.ip_network(value.strip(), strict=False)
    except ValueError:
        raise ActionError("invalid_params", f"{field} must be an IP address or network")
    if net.num_addresses > (2 ** 16 if net.version == 4 else 2 ** 80):
        raise ActionError("invalid_params", f"{field} is too large a range (at most /16 for IPv4, /48 for IPv6)")
    return net


def _allow_entry(item):
    if isinstance(item, str):
        item = {"address": item}
    if not isinstance(item, dict):
        raise ActionError("invalid_params", "allowlist entries must be objects")
    comment = v.string(item, "comment", required=False, default="", max_len=120)
    return {"address": str(_network(item.get("address"), "allowlist.address")), "comment": comment}


def _site(item):
    if not isinstance(item, dict):
        raise ActionError("invalid_params", "sites must be objects")
    domain = v.domain(item, "domain")
    allow = item.get("allowlist") or []
    if not isinstance(allow, list) or len(allow) > 50:
        raise ActionError("invalid_params", f"sites.{domain}.allowlist must be a list of at most 50 addresses")
    return {
        "domain": domain,
        "enabled": v.boolean(item, "enabled", required=False, default=True),
        "wordpress": v.boolean(item, "wordpress", required=False, default=True),
        "allowlist": sorted({str(_network(a.get("address") if isinstance(a, dict) else a, f"sites.{domain}.allowlist")) for a in allow}),
    }


def parse_config(params):
    services = params.get("services") or {}
    if not isinstance(services, dict):
        raise ActionError("invalid_params", "services must be an object")
    unknown = set(services) - set(SERVICES)
    if unknown:
        raise ActionError("invalid_params", f"Unknown service: {', '.join(sorted(unknown))}")
    allow = v.list_of(params, "allowlist", _allow_entry, required=False, max_items=200)
    sites = v.list_of(params, "sites", _site, required=False, max_items=5000)
    if len({s["domain"] for s in sites}) != len(sites):
        raise ActionError("invalid_params", "A site is listed twice")
    return {
        "services": {name: _service(services, name) for name in SERVICES},
        "permanent_days": v.integer(params, "permanent_days", required=False, default=0, minimum=0, maximum=3650),
        "allowlist": allow,
        "sites": sites,
    }


# ----------------------------------------------------------------- rendering

def _q(value):
    """A string literal for a CrowdSec expression. Values are validated domains and networks."""
    return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'"


def _list(values):
    return "[" + ", ".join(_q(x) for x in values) + "]"


def _doc(obj):
    # JSON is valid YAML, so no YAML library is needed.
    return json.dumps(obj, indent=2, ensure_ascii=False)


def _docs(objs):
    return HEADER + "\n---\n".join(_doc(o) for o in objs) + "\n"


def _leakspeed(window_seconds, count):
    return f"{max(1, round(window_seconds / max(count, 1)))}s"


def _human(seconds):
    return f"{seconds // 3600} hours" if seconds >= 7200 and seconds % 3600 == 0 else f"{seconds // 60} minutes"


def _bucket(name, svc, tier, count, window_seconds, extra_filter, blackhole):
    meta = SERVICES[svc]
    flt = f"({meta['filter']})" + (f" && {extra_filter}" if extra_filter else "")
    labels = {
        "service": svc,
        "remediation": True,
        "confidence": 3,
        "spoofable": 0,
        "classification": ["attack.T1110"],
        "behavior": meta["behavior"],
        "label": meta["label"] + (" (permanent)" if tier == "perm" else ""),
        "whp_tier": tier,
    }
    if count <= 1:
        return {"type": "trigger", "name": name, "description": meta["label"], "filter": flt,
                "groupby": "evt.Meta.source_ip", "blackhole": blackhole, "labels": labels}
    return {
        "type": "leaky",
        "name": name,
        "description": f"{meta['label']}: {count} failures within {_human(window_seconds)}",
        "filter": flt,
        "groupby": "evt.Meta.source_ip",
        "capacity": count - 1,  # the bucket overflows on the event after it is full
        "leakspeed": _leakspeed(window_seconds, count),
        "blackhole": blackhole,
        "reprocess": False,
        "labels": labels,
    }


def render_scenarios(cfg):
    wp_off = [s["domain"] for s in cfg["sites"] if not s["wordpress"]]
    docs = []
    for svc, s in cfg["services"].items():
        if not s["enabled"]:
            continue
        extra = f"!({SITE_EXPR} in {_list(wp_off)})" if svc == "wordpress" and wp_off else ""
        docs.append(_bucket(f"whp/{svc}-bf", svc, "temp", s["temp_after"], s["window_minutes"] * 60, extra,
                            f"{min(s['ban_minutes'], 60)}m"))
        if s["perm_after"]:
            docs.append(_bucket(f"whp/{svc}-bf-perm", svc, "perm", s["perm_after"], s["perm_window_hours"] * 3600,
                                extra, "1m"))
    if not docs:
        return HEADER + "# All login protection is switched off.\n"
    return _docs(docs)


def render_profiles(cfg):
    permanent = f"{cfg['permanent_days'] * 24}h" if cfg["permanent_days"] else PERMANENT
    docs = []
    perm = []
    for svc, s in cfg["services"].items():
        if not s["enabled"]:
            continue
        docs.append({
            "name": f"whp_{svc}_temporary",
            "filters": [f'Alert.Remediation == true && Alert.GetScope() == "Ip" && Alert.GetScenario() == "whp/{svc}-bf"'],
            "decisions": [{"type": "ban", "duration": f"{s['ban_minutes']}m"}],
            "on_success": "break",
        })
        if s["perm_after"]:
            perm.append(f"whp/{svc}-bf-perm")
    if perm:
        docs.append({
            "name": "whp_permanent",
            "filters": ['Alert.Remediation == true && Alert.GetScope() == "Ip" && Alert.GetScenario() in '
                        + json.dumps(perm)],
            "decisions": [{"type": "ban", "duration": permanent}],
            "on_success": "break",
        })
    return _docs(docs + STOCK_PROFILES)


def render_allowlists(cfg):
    expressions = []
    off = [s["domain"] for s in cfg["sites"] if not s["enabled"]]
    if off:
        expressions.append(f"{SITE_EXPR} in {_list(off)}")
    for s in cfg["sites"]:
        if not s["allowlist"]:
            continue
        d = s["domain"]
        ips = "any(" + _list(s["allowlist"]) + ", {IpInRange(evt.Meta.source_ip, #)})"
        owner = (f"({SITE_EXPR} == {_q(d)}"
                 f" || lower(evt.Parsed.dovecot_user) endsWith {_q('@' + d)}"
                 f" || lower(evt.Meta.sasl_username) endsWith {_q('@' + d)})")
        expressions.append(f"{ips} && {owner}")
    whitelist = {"reason": "Webhosting Panel allowlist"}
    admin = [a["address"] for a in cfg["allowlist"]]
    if admin:
        whitelist["cidr"] = admin
    if expressions:
        whitelist["expression"] = expressions
    if len(whitelist) == 1:
        return HEADER + "# Nothing is allowlisted.\n"
    return _docs([{
        "name": "whp/allowlists",
        "description": "Admin allowlist, sites with protection off and customer allowlists",
        "whitelist": whitelist,
    }])


