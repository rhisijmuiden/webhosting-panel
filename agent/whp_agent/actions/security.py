# ------------------------------------------------------------------- applying

def _read(path):
    try:
        return path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return None


def _write(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + ".whp-new")
    tmp.write_text(content, encoding="utf-8")
    os.chmod(tmp, 0o644)
    os.replace(tmp, path)


def _backup_stock_profiles():
    """Keep the package's profiles.yaml once, so it can be restored by hand."""
    src = CROWDSEC_DIR / "profiles.yaml"
    dst = CROWDSEC_DIR / "profiles.yaml.whp-orig"
    old = _read(src)
    if old is not None and not dst.exists() and not old.startswith(HEADER):
        _write(dst, old)


def _sync_lapi_allowlist(cfg):
    """Best effort: needs CrowdSec 1.6.8 or newer. Returns a warning or None."""
    run([CSCLI, "allowlists", "delete", ALLOWLIST], timeout=30, check=False)
    entries = cfg["allowlist"]
    if not entries:
        return None
    made = run([CSCLI, "allowlists", "create", ALLOWLIST, "-d", "Managed by the Webhosting Panel"], timeout=30, check=False)
    if made.returncode != 0:
        return "This CrowdSec version has no LAPI allowlists; the community blocklist can still block allowlisted addresses."
    for entry in entries:
        argv = [CSCLI, "allowlists", "add", ALLOWLIST, entry["address"]]
        if entry["comment"]:
            argv += ["-d", entry["comment"]]
        run(argv, timeout=30, check=False)
    return None


def _unban(network):
    flag = "--ip" if network.num_addresses == 1 else "--range"
    value = str(network.network_address) if network.num_addresses == 1 else str(network)
    run([CSCLI, "decisions", "delete", flag, value], timeout=30, check=False)


def _previous_state():
    try:
        return json.loads(STATE_FILE.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def _ensure_auth_log():
    """The panel (user whp) appends failed logins here; CrowdSec tails it."""
    log = Path(PANEL_AUTH_LOG)
    if log.exists():
        return
    log.parent.mkdir(parents=True, exist_ok=True)
    log.touch(mode=0o640)
    try:
        import pwd

        pw = pwd.getpwnam(os.environ.get("WHP_PANEL_USER", "whp"))
        os.chown(log, pw.pw_uid, pw.pw_gid)
    except (KeyError, PermissionError):
        pass


@action("security.apply")
def apply(params):
    cfg = parse_config(params)
    if not Path(CSCLI).exists():
        raise ActionError("not_found", "CrowdSec is not installed")
    files = render_all(cfg)
    _backup_stock_profiles()
    previous = {path: _read(path) for path in files}
    changed = [str(p) for p, content in files.items() if previous[p] != content]
    for path, content in files.items():
        if previous[path] != content:
            _write(path, content)
    _ensure_auth_log()
    if changed:
        check = run([CROWDSEC, "-c", str(CROWDSEC_DIR / "config.yaml"), "-t"], timeout=120, check=False)
        if check.returncode != 0:
            for path, old in previous.items():
                if old is None:
                    path.unlink(missing_ok=True)
                else:
                    _write(path, old)
            raise ActionError("command_failed", "CrowdSec rejected the new configuration; nothing was changed",
                              {"stderr": (check.stderr or check.stdout)[-2000:]})
    before = _previous_state().get("allowlist")
    warning = None
    if before != cfg["allowlist"]:
        warning = _sync_lapi_allowlist(cfg)
        old = {a["address"] for a in before or []}
        for entry in cfg["allowlist"]:
            if entry["address"] not in old:
                _unban(ipaddress.ip_network(entry["address"]))
    if changed:
        run(["systemctl", "reload-or-restart", "crowdsec"], timeout=120)
    STATE_FILE.parent.mkdir(parents=True, exist_ok=True)
    tmp = STATE_FILE.with_name(STATE_FILE.name + ".tmp")
    tmp.write_text(json.dumps({"applied_at": int(time.time()), **cfg}, indent=2), encoding="utf-8")
    os.replace(tmp, STATE_FILE)
    return {"changed": changed, "warning": warning}


# ---------------------------------------------------------- reading activity

def _json(argv):
    out = run([CSCLI, *argv, "-o", "json"], timeout=60).stdout.strip()
    return json.loads(out) if out and out != "null" else []


def _meta_values(items, key):
    """Alert meta and event meta are lists of {key, value}; alert meta values are JSON lists."""
    found = set()
    for m in items or []:
        if m.get("key") != key:
            continue
        val = m.get("value") or ""
        try:
            parsed = json.loads(val)
        except ValueError:
            parsed = val
        for x in parsed if isinstance(parsed, list) else [parsed]:
            if isinstance(x, str) and x:
                found.add(x.lower())
    return found


def _belongs(alert, domain):
    sites = _meta_values(alert.get("meta"), "whp_site")
    users = _meta_values(alert.get("meta"), "whp_user")
    for ev in alert.get("events") or []:
        sites |= _meta_values(ev.get("meta"), "whp_site")
        users |= _meta_values(ev.get("meta"), "sasl_username") | _meta_values(ev.get("meta"), "target_user")
    return domain in sites or any(u.endswith("@" + domain) for u in users)


def _alerts(extra):
    return _json(["alerts", "list", "--limit", "1000", *extra])


@action("security.site_activity")
def site_activity(params):
    """Recent attacks on one site (and its mailboxes), for the customer."""
    domain = v.domain(params, "domain")
    days = v.integer(params, "days", required=False, default=7, minimum=1, maximum=30)
    rows = []
    for alert in _alerts(["--since", f"{days * 24}h"]):
        if not _belongs(alert, domain):
            continue
        source = alert.get("source") or {}
        active = [d for d in alert.get("decisions") or [] if d.get("type") == "ban"]
        rows.append({
            "address": source.get("ip") or source.get("value"),
            "country": source.get("cn"),
            "scenario": alert.get("scenario"),
            "events": alert.get("events_count"),
            "at": alert.get("created_at") or alert.get("start_at"),
            "blocked_for": active[0].get("duration") if active else None,
        })
    rows.sort(key=lambda r: r["at"] or "", reverse=True)
    return {"domain": domain, "days": days, "alerts": rows[:200]}


@action("security.site_release")
def site_release(params):
    """Lift blocks on one address that were caused by this site or its mailboxes.

    Used when a customer adds their own address to the site's allowlist.
    Blocks from other sources (SSH, the community blocklist) stay.
    """
    domain = v.domain(params, "domain")
    net = _network(params.get("address"), "address")
    if net.num_addresses != 1:
        return {"released": 0}
    ip = str(net.network_address)
    released = 0
    for alert in _alerts(["--ip", ip, "--since", "8760h"]):
        if not _belongs(alert, domain):
            continue
        for d in alert.get("decisions") or []:
            if d.get("id") is not None:
                run([CSCLI, "decisions", "delete", "--id", str(int(d["id"]))], timeout=30, check=False)
                released += 1
    return {"address": ip, "released": released}


@action("security.check_ip")
def check_ip(params):
    """Is this address blocked right now, and why."""
    net = _network(params.get("address"), "address")
    if net.num_addresses != 1:
        raise ActionError("invalid_params", "address must be a single IP address")
    rows = _json(["decisions", "list", "--ip", str(net.network_address)])
    out = []
    for alert in rows or []:
        for d in alert.get("decisions") or []:
            out.append({"scenario": d.get("scenario") or alert.get("scenario"), "duration": d.get("duration"),
                        "origin": d.get("origin")})
    return {"address": str(net.network_address), "blocked": bool(out), "decisions": out}
