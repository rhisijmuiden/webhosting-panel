"""Login protection: brute-force thresholds, per-site toggles and allowlists.

The panel owns the settings and sends all of them with every
``security.apply``. The agent turns them into CrowdSec configuration:

* ``scenarios/whp-login.yaml``: two leaky buckets per service. ``whp/<svc>-bf``
  overflows after ``temp_after`` failed logins within ``window_minutes`` and
  leads to a temporary ban; ``whp/<svc>-bf-perm`` overflows after
  ``perm_after`` failures within ``perm_window_hours`` and leads to a
  permanent ban.
* ``profiles.yaml``: our profiles (ban durations per scenario) in front of the
  stock CrowdSec profiles.
* ``parsers/s01-parse/whp-panel-auth.yaml``: failed panel logins, which the
  panel writes to ``/var/log/webhosting-panel/auth.log``.
* ``parsers/s02-enrich/whp-site.yaml``: tags web events with the site
  (``evt.Meta.whp_site``) from the per-site log path.
* ``parsers/s02-enrich/whp-allowlists.yaml``: admin allowlist, sites with
  protection switched off, and the per-site customer allowlists.
* ``postoverflows/s01-whitelist/whp-hub-overrides.yaml``: drops alerts of the
  hub's own login brute-force scenarios, so the panel thresholds are the only
  ones that count for logins.
* ``contexts/whp.yaml``: keeps site and user on alerts, for the customer view.
* LAPI allowlist ``whp-panel``: the admin allowlist also beats the community
  blocklist.

Everything is validated with ``crowdsec -t`` before CrowdSec is reloaded; on a
failure the previous files are put back.
"""

