"""Panel-managed firewall rules.

The installer owns the base ruleset (table inet whp, policy drop, fixed
ports). The panel only adds elements to the installer's sets, through
/etc/nftables.d/whp-panel.nft, generated from firewall.json.
"""

import ipaddress
import json
import os
import time
import uuid

from .. import paths
from .. import validate as v
from ..registry import ActionError, action
from ..run import run

RULES_FILE = os.path.join(paths.CONFIG_DIR, "firewall.json")
NFT_FILE = os.path.join(paths.NFT_DIR, "whp-panel.nft")
# Ports the installer keeps open itself; the panel may not remove them.
PROTECTED_TCP = {"22", "25", "80", "443", "465", "587", "993", "8443"}


def _load():
    try:
        with open(RULES_FILE) as fh:
            return json.load(fh)
    except FileNotFoundError:
        return {"rules": []}


def _render(rules):
    lines = ["# Generated by whp-agent from firewall.json. Do not edit by hand.", ""]
    for rule in rules:
        if rule["type"] == "open_port":
            set_name = "tcp_open" if rule["protocol"] == "tcp" else "udp_open"
            lines.append(f"add element inet whp {set_name} {{ {rule['port']} }}  # {rule['id']}")
        elif rule["type"] == "block_ip":
            net = ipaddress.ip_network(rule["address"])
            set_name = "blocked_v4" if net.version == 4 else "blocked_v6"
            lines.append(f"add element inet whp {set_name} {{ {net} }}  # {rule['id']}")
    return "\n".join(lines) + "\n"


def _save_and_apply(data):
    os.makedirs(paths.CONFIG_DIR, exist_ok=True)
    os.makedirs(paths.NFT_DIR, exist_ok=True)
    content = _render(data["rules"])
    tmp = NFT_FILE + ".new"
    with open(tmp, "w") as fh:
        fh.write(content)
    old = None
    if os.path.exists(NFT_FILE):
        with open(NFT_FILE) as fh:
            old = fh.read()
    os.replace(tmp, NFT_FILE)
    try:
        run(["nft", "-c", "-f", "/etc/nftables.conf"], timeout=20)
    except ActionError:
        if old is None:
            os.unlink(NFT_FILE)
        else:
            with open(NFT_FILE, "w") as fh:
                fh.write(old)
        raise
    with open(RULES_FILE + ".tmp", "w") as fh:
        json.dump(data, fh, indent=2)
    os.replace(RULES_FILE + ".tmp", RULES_FILE)
    run(["systemctl", "reload", "nftables"], timeout=30)


@action("firewall.list")
def firewall_list(params):
    data = _load()
    return {"rules": data["rules"], "protected_tcp_ports": sorted(PROTECTED_TCP, key=int)}


@action("firewall.add")
def firewall_add(params):
    rule_type = v.choice(params, "type", ["open_port", "block_ip"])
    comment = v.string(params, "comment", required=False, default="", max_len=120)
    rule = {"id": uuid.uuid4().hex[:12], "type": rule_type, "comment": comment, "created_at": int(time.time())}
    if rule_type == "open_port":
        rule["protocol"] = v.choice(params, "protocol", ["tcp", "udp"])
        rule["port"] = str(v.integer(params, "port", minimum=1, maximum=65535))
    else:
        rule["address"] = v.ip_or_network(params, "address")
    data = _load()
    for existing in data["rules"]:
        same = {k: existing.get(k) for k in ("type", "protocol", "port", "address")}
        if same == {k: rule.get(k) for k in ("type", "protocol", "port", "address")}:
            raise ActionError("conflict", "This rule already exists")
    data["rules"].append(rule)
    _save_and_apply(data)
    return rule


@action("firewall.delete")
def firewall_delete(params):
    rule_id = v.string(params, "id", max_len=32, pattern=r"[0-9a-f]{12}")
    data = _load()
    remaining = [r for r in data["rules"] if r["id"] != rule_id]
    if len(remaining) == len(data["rules"]):
        raise ActionError("not_found", "Rule not found")
    data["rules"] = remaining
    _save_and_apply(data)
    return {"deleted": rule_id}
